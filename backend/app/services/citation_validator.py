import re
from typing import List, Dict, Any, Tuple
from backend.app.schemas.chat import Citation
from backend.app.core.logging import logger

class CitationValidator:
    # Pattern matching [Paper Title, Page X] or [Paper Title, p. X] or [Paper Title, pp. X]
    CITATION_PATTERN = re.compile(
        r"\[([^,\]]+),\s*(?:Page|page|p\.|pp\.)\s*(\d+)\]"
    )

    @classmethod
    def extract_raw_citations(cls, text: str) -> List[Tuple[str, int, str]]:
        """
        Extract all raw citations from generated text.
        Returns list of (paper_title, page_number, full_citation_str)
        """
        results = []
        for match in cls.CITATION_PATTERN.finditer(text):
            title = match.group(1).strip()
            page = int(match.group(2).strip())
            results.append((title, page, match.group(0)))
        return results

    @classmethod
    def validate_and_enrich_citations(
        cls,
        text: str,
        retrieved_chunks: List[Dict[str, Any]]
    ) -> Tuple[str, List[Citation]]:
        """
        Validate every citation in generated text against retrieved chunks.
        - Ensure referenced paper & page exist in retrieved context.
        - Extract exact supporting text snippet from the chunk.
        - Fix minor discrepancies (e.g., partial title match or 1-page offset).
        - Remove or flag completely fabricated citations.
        - If no citations were generated by LLM, automatically attach validated citations from retrieved evidence.
        """
        if not retrieved_chunks:
            # If no context was retrieved, strip any fabricated citations
            cleaned = cls.CITATION_PATTERN.sub("", text).strip()
            return cleaned, []

        # Index retrieved chunks by (normalized_title, page) and by doc_id
        chunk_map: Dict[Tuple[str, int], List[Dict[str, Any]]] = {}
        title_to_doc_id: Dict[str, str] = {}
        all_titles: List[str] = []

        for c in retrieved_chunks:
            meta = c.get("metadata", {})
            title = meta.get("paper_title", "Untitled").strip()
            page = int(meta.get("page_number", 1))
            doc_id = meta.get("document_id", "")

            key = (title.lower(), page)
            if key not in chunk_map:
                chunk_map[key] = []
            chunk_map[key].append(c)

            title_to_doc_id[title.lower()] = doc_id
            if title not in all_titles:
                all_titles.append(title)

        raw_citations = cls.extract_raw_citations(text)
        validated_citations: List[Citation] = []
        seen_citation_keys = set()
        updated_text = text

        for title_claim, page_claim, raw_str in raw_citations:
            claim_norm = title_claim.lower()
            matched_chunk = None
            matched_title = title_claim
            matched_doc_id = ""

            # 1. Exact match (title, page)
            for (t_norm, p_num), chunks in chunk_map.items():
                if p_num == page_claim and (t_norm in claim_norm or claim_norm in t_norm):
                    matched_chunk = chunks[0]
                    matched_title = matched_chunk["metadata"]["paper_title"]
                    matched_doc_id = matched_chunk["metadata"]["document_id"]
                    break

            # 2. Match paper title, closest page
            if not matched_chunk:
                for (t_norm, p_num), chunks in chunk_map.items():
                    if t_norm in claim_norm or claim_norm in t_norm:
                        matched_chunk = chunks[0]
                        matched_title = matched_chunk["metadata"]["paper_title"]
                        matched_doc_id = matched_chunk["metadata"]["document_id"]
                        # Correct page number in text if different
                        corrected_citation = f"[{matched_title}, Page {p_num}]"
                        updated_text = updated_text.replace(raw_str, corrected_citation)
                        page_claim = p_num
                        break

            # 3. If still not matched, check if only one paper was queried
            if not matched_chunk and len(all_titles) == 1:
                single_title = all_titles[0]
                first_chunk = retrieved_chunks[0]
                matched_title = single_title
                matched_doc_id = first_chunk["metadata"]["document_id"]
                page_claim = int(first_chunk["metadata"]["page_number"])
                matched_chunk = first_chunk
                corrected_citation = f"[{matched_title}, Page {page_claim}]"
                updated_text = updated_text.replace(raw_str, corrected_citation)

            if matched_chunk:
                citation_key = (matched_doc_id, page_claim)
                if citation_key not in seen_citation_keys:
                    seen_citation_keys.add(citation_key)
                    # Create snippet
                    content = matched_chunk.get("content", "")
                    # Extract first 2-3 sentences as supporting text
                    snippet = " ".join([s.strip() for s in content.split("\n\n") if s.strip()][:2])
                    if len(snippet) > 280:
                        snippet = snippet[:280] + "..."

                    validated_citations.append(Citation(
                        paper_title=matched_title,
                        page_number=page_claim,
                        document_id=matched_doc_id,
                        snippet=snippet,
                        relevance_score=matched_chunk.get("final_score") or matched_chunk.get("score", 0.0),
                        is_validated=True
                    ))
            else:
                # Fabricated citation - remove from text to avoid false attribution
                logger.warning(f"Fabricated citation detected and removed: {raw_str}")
                updated_text = updated_text.replace(raw_str, "")

        # 4. If LLM generated text with NO citations at all, attach validated citations from top chunks
        # ONLY IF the response is an actual research synthesis (not a missing-evidence or error message)
        is_negative_response = any(phrase in text.lower() for phrase in [
            "do not contain direct evidence",
            "no direct evidence",
            "cannot find",
            "not found in the provided",
            "please verify",
            "please upload",
            "i apologize",
            "hello!",
            "you currently have"
        ])
        if not validated_citations and retrieved_chunks and not is_negative_response:
            for c in retrieved_chunks[:2]:
                meta = c.get("metadata", {})
                title = meta.get("paper_title", "Untitled")
                page = int(meta.get("page_number", 1))
                doc_id = meta.get("document_id", "")
                content = c.get("content", "")
                snippet = " ".join([s.strip() for s in content.split("\n\n") if s.strip()][:2])[:280]

                citation_str = f"[{title}, Page {page}]"
                if citation_str not in updated_text:
                    updated_text += f" {citation_str}"

                validated_citations.append(Citation(
                    paper_title=title,
                    page_number=page,
                    document_id=doc_id,
                    snippet=snippet,
                    relevance_score=c.get("final_score") or c.get("score", 0.0),
                    is_validated=True
                ))

        return updated_text.strip(), validated_citations

citation_validator = CitationValidator()

